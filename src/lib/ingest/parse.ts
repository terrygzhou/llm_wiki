export function sourceSummaryMediaRefsForExternalMarkdown(content: string): string {
  return content
    .replace(/(\]\()\.?\/?media\//g, "$1../media/")
    .replace(/(\bsrc=["'])\.?\/?media\//gi, "$1../media/")
}

